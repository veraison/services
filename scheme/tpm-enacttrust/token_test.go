func TestToken_Decode_signature_check(t *testing.T) {
	data := []byte{ // nolint:prealloc
		0x7d, 0xf7, 0x71, 0x4e, 0xaa, 0x04, 0x46, 0x38, // 16-byte node ID
		0xbc, 0xbf, 0x43, 0x4b, 0x1d, 0xd7, 0x20, 0xf1,
		0x00, 0x4f, // size = 79
		0xff, 0x54, 0x43, 0x47, 0x80, 0x18, 0x00, 0x00, // 79-byte TPMS_ATTEST
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x07, 0x00, 0x00, 0x00, 0x01, 0x00,
		0x0b, 0x03, 0x1e, 0x00, 0x00, 0x00, 0x20, 0x87,
		0x42, 0x8f, 0xc5, 0x22, 0x80, 0x3d, 0x31, 0x06,
		0x5e, 0x7b, 0xce, 0x3c, 0xf0, 0x3f, 0xe4, 0x75,
		0x09, 0x66, 0x31, 0xe5, 0xe0, 0x7b, 0xbd, 0x7a,
		0x0f, 0xde, 0x60, 0xc4, 0xcf, 0x25, 0xc7,
		// no signature
	}

	sig := tpm2.Signature{
		Alg: tpm2.AlgRSASSA,
		RSA: &tpm2.SignatureRSA{
			HashAlg: tpm2.AlgSHA256,
			Signature: tpmutil.U16Bytes{
				0xde, 0xad, 0xbe, 0xef, 0xde, 0xad, 0xbe, 0xef,
				0xde, 0xad, 0xbe, 0xef, 0xde, 0xad, 0xbe, 0xef,
			},
		},
	}

	sigEncoded, err := sig.Encode()
	assert.NoError(t, err)

	data = append(data, sigEncoded...)
	var token Token
	err = token.Decode(data)

	assert.ErrorContains(t, err, "invalid TPMT_SIGNATURE: invalid alg: 20 (must be 24 (ECDSA))")
}

func Test_validateSignatureFormat(t *testing.T) {
	testCases := []struct{
		title string
		sig tpm2.Signature
		err string
	}{
		{
			title: "ok",
			sig: tpm2.Signature{
				Alg: tpm2.AlgECDSA,
				ECC: &tpm2.SignatureECC{
					HashAlg: tpm2.AlgSHA256,
					R: big.NewInt(0).SetBytes([]byte{
						0xde, 0xad, 0xbe, 0xef, 0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef, 0xde, 0xad, 0xbe, 0xef,
					}),
					S: big.NewInt(0).SetBytes([]byte{
						0xc0, 0xde, 0xca, 0xfe, 0xc0, 0xde, 0xca, 0xfe,
						0xc0, 0xde, 0xca, 0xfe, 0xc0, 0xde, 0xca, 0xfe,
					}),
				},
			},
		},
		{
			title: "err wrong alg",
			sig: tpm2.Signature{
				Alg: tpm2.AlgRSASSA,
				RSA: &tpm2.SignatureRSA{
					HashAlg: tpm2.AlgSHA256,
					Signature: tpmutil.U16Bytes{
						0xde, 0xad, 0xbe, 0xef, 0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef, 0xde, 0xad, 0xbe, 0xef,
					},
				},
			},
			err: "invalid alg: 20 (must be 24 (ECDSA))",
		},
		{
			title: "err no ECC",
			sig: tpm2.Signature{
				Alg: tpm2.AlgECDSA,
			},
			err: "missing ECC signature",
		},
		{
			title: "err wrong hash alg",
			sig: tpm2.Signature{
				Alg: tpm2.AlgECDSA,
				ECC: &tpm2.SignatureECC{
					HashAlg: tpm2.AlgSHA384,
					R: big.NewInt(0).SetBytes([]byte{
						0xde, 0xad, 0xbe, 0xef, 0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef, 0xde, 0xad, 0xbe, 0xef,
					}),
					S: big.NewInt(0).SetBytes([]byte{
						0xc0, 0xde, 0xca, 0xfe, 0xc0, 0xde, 0xca, 0xfe,
						0xc0, 0xde, 0xca, 0xfe, 0xc0, 0xde, 0xca, 0xfe,
					}),
				},
			},
			err: "unsupported hash alg: 12 (only 11 (SHA256) is supported)",
		},
		{
			title: "err missing signature component",
			sig: tpm2.Signature{
				Alg: tpm2.AlgECDSA,
				ECC: &tpm2.SignatureECC{
					HashAlg: tpm2.AlgSHA256,
					R: big.NewInt(0).SetBytes([]byte{
						0xde, 0xad, 0xbe, 0xef, 0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef, 0xde, 0xad, 0xbe, 0xef,
					}),
				},
			},
			err: "missing ECC signature component(s)",
		},
	}

	for _, tc := range testCases {
		t.Run(tc.title, func(t *testing.T) {
			err := validateSignatureFormat(&tc.sig)
			if tc.err == "" {
				assert.NoError(t, err)
			} else {
				assert.ErrorContains(t, err, tc.err)
			}
		})
	}
}

func TestToken_Decode_size_check(t *testing.T) {
	testCases := []struct{
		title string
		data []byte
		err string
	}{
		{
			title: "err truncated TPMS_ATTEST",
			data: []byte{
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // 16-byte node ID
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
				0x00, 0x01, // size = 1
				// no data follows
			},
			err: "TPMS_ATTEST appears truncated",
		},
		{
			title: "err no signature",
			data: []byte{
				0x7d, 0xf7, 0x71, 0x4e, 0xaa, 0x04, 0x46, 0x38, // 16-byte node ID
				0xbc, 0xbf, 0x43, 0x4b, 0x1d, 0xd7, 0x20, 0xf1,
				0x00, 0x4f, // size = 79
				0xff, 0x54, 0x43, 0x47, 0x80, 0x18, 0x00, 0x00, // 79-byte TPMS_ATTEST
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
				0x00, 0x00, 0x07, 0x00, 0x00, 0x00, 0x01, 0x00,
				0x0b, 0x03, 0x1e, 0x00, 0x00, 0x00, 0x20, 0x87,
				0x42, 0x8f, 0xc5, 0x22, 0x80, 0x3d, 0x31, 0x06,
				0x5e, 0x7b, 0xce, 0x3c, 0xf0, 0x3f, 0xe4, 0x75,
				0x09, 0x66, 0x31, 0xe5, 0xe0, 0x7b, 0xbd, 0x7a,
				0x0f, 0xde, 0x60, 0xc4, 0xcf, 0x25, 0xc7,
				// no signature
			},
			err: "could not decode TPMT_SIGNATURE: decoding Alg: EOF",
		},
	}

	for _, tc := range testCases {
		t.Run(tc.title, func(t *testing.T) {
			var err error
			assert.NotPanics(t, func() {
				var token Token
				err = token.Decode(tc.data)
			})

			assert.ErrorContains(t, err, tc.err)
		})
	}
}
